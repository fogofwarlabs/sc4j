package org.fogofwarlabs.sc4j.launcher.ui.form;

import javafx.beans.property.ReadOnlyIntegerProperty;
import javafx.beans.property.ReadOnlyIntegerWrapper;
import javafx.scene.control.Label;
import javafx.scene.layout.HBox;
import javafx.scene.layout.Region;
import javafx.scene.layout.VBox;
import org.fogofwarlabs.sc4j.launcher.form.FormField;
import org.fogofwarlabs.sc4j.launcher.form.SettingsForm;
import org.fogofwarlabs.sc4j.launcher.i18n.LauncherTexts;
import org.fogofwarlabs.sc4j.launcher.ui.ComponentUtils;
import org.fogofwarlabs.sc4j.launcher.ui.ThemeUtils;
import org.fogofwarlabs.sc4j.manifest.settings.SettingDefinition;
import org.fogofwarlabs.sc4j.manifest.settings.SettingType;
import org.fogofwarlabs.sc4j.manifest.text.LocalizedText;
import org.jetbrains.annotations.NotNull;

import java.util.ArrayList;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * Shows a {@link SettingsForm}: one field per setting, generated by the {@link FieldControlFactory} of the setting's type,
 * with the label (and a required mark), the control, the validation message and the description. Every change validates
 * the field through the form, updates the count of invalid fields, which blocks the Run button, and is reported to the owner, which saves
 * the values.
 */
public final class SettingsFormView {
    private static final @NotNull Map<@NotNull SettingType, @NotNull FieldControlFactory> FACTORIES = new EnumMap<>(SettingType.class);
    private static final @NotNull String REQUIRED_MARK = " *";

    /**
     * Holds the control and the message label of one shown field.
     */
    private static final class FieldView {
        private final @NotNull FormField field;
        private final @NotNull FieldControl control;
        private final @NotNull Label message;

        /**
         * Creates a {@link FieldView} instance.
         *
         * @param field   the field
         * @param control the field's control
         * @param message the label of the validation message
         */
        private FieldView(@NotNull FormField field, @NotNull FieldControl control, @NotNull Label message) {
            this.field   = field;
            this.control = control;
            this.message = message;
        }
    }

    static {
        FACTORIES.put(SettingType.DIRECTORY, PathControlFactory.DIRECTORY);
        FACTORIES.put(SettingType.FILE, PathControlFactory.FILE);
        FACTORIES.put(SettingType.CHOICE, ChoiceControlFactory.INSTANCE);
        FACTORIES.put(SettingType.BOOLEAN, BooleanControlFactory.INSTANCE);
        FACTORIES.put(SettingType.INTEGER, IntegerControlFactory.INSTANCE);
        FACTORIES.put(SettingType.STRING, StringControlFactory.INSTANCE);
    }


    private final @NotNull SettingsForm form;
    private final @NotNull LauncherTexts texts;
    private final @NotNull Runnable onChange;
    private final @NotNull List<@NotNull FieldView> fieldViews;
    private final @NotNull ReadOnlyIntegerWrapper invalidCount;
    private final @NotNull VBox root;

    /**
     * Creates a {@link SettingsFormView} instance with a control for every field of the form.
     *
     * @param form     the form
     * @param texts    the launcher texts of the display language
     * @param onChange called after a field changed and after a reset to the defaults, with the form holding the new values
     */
    public SettingsFormView(@NotNull SettingsForm form, @NotNull LauncherTexts texts, @NotNull Runnable onChange) {
        this.form         = form;
        this.texts        = texts;
        this.onChange     = onChange;
        this.fieldViews   = new ArrayList<>();
        this.invalidCount = new ReadOnlyIntegerWrapper();
        this.root         = ComponentUtils.createForm();

        if (form.getFields().isEmpty()) {
            this.root.getChildren().add(ComponentUtils.createParagraph(texts.get("form.empty"), "text-caption"));
        }

        for (FormField field : form.getFields()) {
            this.root.getChildren().add(this.createField(field));
        }

        this.showValidation();
    }

    /**
     * @return the form's root node
     */
    public @NotNull VBox getRoot() {
        return this.root;
    }

    /**
     * @return the number of invalid fields; the mod may start only at zero
     */
    public @NotNull ReadOnlyIntegerProperty invalidCountProperty() {
        return this.invalidCount.getReadOnlyProperty();
    }

    /**
     * Sets every field back to its default, shows the result and reports the change.
     */
    public void resetToDefaults() {
        this.form.resetToDefaults();

        for (FieldView view : this.fieldViews) {
            view.control.showValue();
        }

        this.showValidation();
        this.onChange.run();
    }

    /**
     * Validates every field again, for example after files changed on disk, and shows the result.
     */
    public void validate() {
        this.form.validate();
        this.showValidation();
    }

    private @NotNull VBox createField(@NotNull FormField field) {
        SettingDefinition definition = field.getDefinition();
        FieldControl control = FACTORIES.get(definition.getType()).create(field, this.texts, this::reportChange);
        Label message = ComponentUtils.createLabel("", "field-message");
        Region messageIcon = new Region();
        LocalizedText description = definition.getDescription();
        VBox fieldNode = new VBox();

        messageIcon.getStyleClass().add("field-message-icon");
        message.setGraphic(messageIcon);
        message.setWrapText(true);
        fieldNode.getStyleClass().add("field");

        if (!control.isLabelled()) {
            HBox labelRow = new HBox(ComponentUtils.createLabel(this.texts.localize(definition.getLabel()), "field-label"));

            if (definition.isRequired()) {
                labelRow.getChildren().add(ComponentUtils.createLabel(REQUIRED_MARK, "field-required"));
            }

            fieldNode.getChildren().add(labelRow);
        }

        fieldNode.getChildren().addAll(control.getNode(), message);

        if (description != null) {
            fieldNode.getChildren().add(ComponentUtils.createParagraph(this.texts.localize(description), "field-help"));
        }

        this.fieldViews.add(new FieldView(field, control, message));

        return fieldNode;
    }

    private void reportChange() {
        this.showValidation();
        this.onChange.run();
    }

    private void showValidation() {
        int invalid = 0;

        for (FieldView view : this.fieldViews) {
            String problem = view.field.describeProblem(this.texts);
            boolean failed = problem != null;

            view.control.getInput().pseudoClassStateChanged(ThemeUtils.INVALID, failed);
            view.message.setText(failed ? problem : "");
            view.message.setVisible(failed);
            view.message.setManaged(failed);

            if (failed) {
                invalid++;
            }
        }

        this.invalidCount.set(invalid);
    }
}

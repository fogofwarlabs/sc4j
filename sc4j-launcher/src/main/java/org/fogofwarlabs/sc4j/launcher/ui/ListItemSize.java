package org.fogofwarlabs.sc4j.launcher.ui;

/**
 * Lists the sizes of list items ({@link ListItem}): the regular item and a compact item with less padding and a smaller title, for long lists
 * of short rows.
 */
public enum ListItemSize {
    /**
     * The regular item.
     */
    REGULAR,
    /**
     * The compact item.
     */
    COMPACT
}
